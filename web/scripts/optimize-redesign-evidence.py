"""Preserve screenshot layout/content using smaller, lossy WebP files.

Only docs/redesign/evidence screenshots are processed; UI content and dimensions
are unchanged. Pillow is a validation-tool dependency, not a frontend dependency.
"""
from pathlib import Path
from PIL import Image
import json
root = Path(__file__).resolve().parents[2]
folder = root / 'docs/redesign/evidence'
changes = []
for source in sorted(folder.iterdir()):
    if source.suffix.lower() not in {'.png', '.jpg', '.jpeg'}:
        continue
    target = source.with_suffix('.webp')
    image = Image.open(source).convert('RGB')
    before = source.stat().st_size
    image.save(target, 'WEBP', quality=74, method=6)
    changes.append({'before': str(source.relative_to(root)), 'after': str(target.relative_to(root)), 'beforeBytes': before, 'afterBytes': target.stat().st_size, 'width': image.width, 'height': image.height})
    source.unlink()
for report in folder.glob('*.json'):
    content = report.read_text()
    for row in changes:
        content = content.replace(row['before'], row['after'])
        content = content.replace(Path(row['before']).name, Path(row['after']).name)
    report.write_text(content)
if changes:
    previous = folder / 'optimization.json'
    rows = json.loads(previous.read_text()).get('images', []) if previous.exists() else []
    rows = [row for row in rows if row['after'] not in {row['after'] for row in changes}]
    previous.write_text(json.dumps({'method': 'Browser screenshot pixels and dimensions retained; WebP quality 74. Original captures are regenerated by browser test scripts.', 'images': rows + changes}, indent=2) + '\n')
print(f'Optimized {len(changes)} screenshots; saved {sum(row["beforeBytes"]-row["afterBytes"] for row in changes):,} bytes.')
